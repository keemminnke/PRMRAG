#!/bin/bash
# 100개 질문 테스트 모니터링 스크립트

echo "=============================================================================="
echo "100개 질문 테스트 모니터링"
echo "=============================================================================="
echo ""

# 프로세스 확인
echo "📊 프로세스 상태:"
ps aux | grep "batch_test_adaptive.py.*100" | grep -v grep | head -3
echo ""

# 로그 파일 크기
if [ -f /tmp/test_100q.log ]; then
    echo "📄 로그 파일 크기: $(wc -l < /tmp/test_100q.log) lines"
    echo ""

    # 진행 중인 질문 확인
    echo "🔍 현재 진행 중인 질문:"
    grep -E "\[[0-9]+/100\] Processing" /tmp/test_100q.log | tail -1
    echo ""

    # 최근 정확도 통계
    echo "✅ 최근 완료된 질문들:"
    grep -E "^  (✅|❌)" /tmp/test_100q.log | tail -10
    echo ""

    # 최근 로그 (마지막 30줄)
    echo "📝 최근 로그 (마지막 30줄):"
    tail -30 /tmp/test_100q.log
else
    echo "⚠️  로그 파일이 아직 생성되지 않았습니다."
    echo "프로세스가 시작 중입니다..."
fi

echo ""
echo "=============================================================================="
echo "모니터링 완료 ($(date))"
echo "=============================================================================="
